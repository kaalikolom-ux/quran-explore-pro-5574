let updatedCount = 0;
for (let ayahNum = 177; ayahNum <= 222; ayahNum++) {
  const p = parsed[ayahNum];
  if (!p) {
    console.error(`Missing parsed data for ayah ${ayahNum}`);
    continue;
  }
  
  const ayahObj = surah2.ayahs.find(a => a.ayah === ayahNum);
  if (!ayahObj) {
    console.error(`Ayah ${ayahNum} not found in surah 2 json!`);
    continue;
  }
  
  ayahObj.meta_bn = metaMap[ayahNum] || p.meta || '';
  ayahObj.modern_translation_bn = p.sciText;
  if (p.tradText && !ayahObj.translation_bn) {
    ayahObj.translation_bn = p.tradText;
  }
  if (lexiconNotes[ayahNum]) {
    ayahObj.lexicon_modern_notes = lexiconNotes[ayahNum];
  }
  
  updatedCount++;
}

